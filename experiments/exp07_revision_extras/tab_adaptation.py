"""Task 1 — LaTeX table for the HUST adaptation result (paper/tables/tab_adaptation.tex).

Reads the exp06 aggregate (study-stratified quantile gate, bank+retrain variant)
and renders it in the same MDPI booktabs/tabularx style as the other paper
tables. Computes nothing: numbers come straight from the run that produced them.

Run:  python -m experiments.exp07_revision_extras.tab_adaptation
"""
from __future__ import annotations

import json

import numpy as np
import pandas as pd

from src.config import ROOT

SRC = ROOT / "outputs" / "experiment_06_quantile_gate"
TABLE = ROOT / "paper" / "tables" / "tab_adaptation.tex"
REF = "study_stratified"
VARIANT = "bank_retrain"


def fmt(mean, std, digits=1, dash_if_nan=True):
    if not np.isfinite(mean):
        return "---" if dash_if_nan else "0"
    if not np.isfinite(std):
        return f"{mean:.{digits}f}"
    return f"${mean:.{digits}f} \\pm {std:.{digits}f}$"


def main() -> None:
    agg = pd.read_csv(SRC / "hust_results_aggregated.csv")
    dep = json.loads((SRC / "deployed_gate.json").read_text())
    q = dep["q_star"]
    s = (agg[(agg.ref_distribution == REF) & (agg.variant == VARIANT)]
         .sort_values("n_added").reset_index(drop=True))
    n_repeats = int(s["n_repeats"].iloc[0])

    rows = []
    for _, r in s.iterrows():
        rows.append(" & ".join([
            str(int(r["n_added"])),
            str(int(r["n_eval"])),
            fmt(r["retention_pct_mean"], r["retention_pct_std"]),
            fmt(r["mape_retained_mean"], r["mape_retained_std"]),
            fmt(r["false_acceptance_mean"], r["false_acceptance_std"]),
            fmt(r["unnecessary_rejection_mean"], r["unnecessary_rejection_std"]),
        ]) + r" \\")

    tex = [
        "% Auto-generated by experiments/exp07_revision_extras/tab_adaptation.py",
        "% — do not edit by hand.",
        r"\begin{table}[H]",
        r"\caption{Small-sample adaptation on the external HUST study under the",
        r"study-stratified quantile gate: a cell is served when its neighborhood",
        r"coverage reaches the $q=" + f"{q:g}" + r"$th percentile of the coverage that",
        r"bank cells from its own study actually attain. The percentile was fixed on",
        r"the Severson in-study cross-validation and is never re-tuned; only the",
        r"neighbor bank and the predictor change. $n$ labeled HUST cells are added to",
        r"the bank at random and the predictor is retrained on Severson $+\,n$;",
        r"evaluation is on the remaining $77-n$ cells. Mean $\pm$ standard deviation",
        f"over {n_repeats} seeded repeats. False acceptances are served predictions with",
        r"absolute percentage error above 30\%; unnecessary rejections are abstentions",
        r"on cells the predictor would have called within that bound. At $n=0$ the bank",
        r"holds no HUST cells, the rule falls back to the whole-bank percentile, and the",
        r"gate abstains on the entire population.\label{tab:adaptation}}",
        r"\begin{tabularx}{\textwidth}{lCCCCC}",
        r"\toprule",
        r"\textbf{$n$ added} & \textbf{Evaluated} & \textbf{Retention (\%)} & "
        r"\textbf{MAPE, retained (\%)} & \textbf{False acc.} & \textbf{Unnec. rej.} \\",
        r"\midrule",
        *rows,
        r"\bottomrule",
        r"\end{tabularx}",
        r"\end{table}",
    ]
    TABLE.parent.mkdir(parents=True, exist_ok=True)
    TABLE.write_text("\n".join(tex) + "\n")
    print(f"[tab_adaptation] -> {TABLE}")
    print("\n".join(tex))


if __name__ == "__main__":
    main()
